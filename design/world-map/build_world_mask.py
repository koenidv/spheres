"""Rasterises Natural Earth 50m land into the RLE land mask used by the pixel map.

Usage: python3 build_world_mask.py ne_50m_land.geojson > WorldMaskData.kt
Source: https://github.com/nvkelso/natural-earth-vector (public domain).
Grid: 0.5 deg per cell, 720 columns, latitude 84N..58S (284 rows).
Rows are encoded as alternating water/land run lengths (base 36, comma separated), rows joined by ';'.
"""
import json
import sys

from PIL import Image, ImageDraw

W, H, SS = 720, 360, 4
TOP_LAT, BOTTOM_LAT = 84, -58

data = json.load(open(sys.argv[1]))
img = Image.new("L", (W * SS, H * SS), 0)
draw = ImageDraw.Draw(img)


def proj(x, y):
    return ((x + 180) / 360 * W * SS, (90 - y) / 180 * H * SS)


for f in data["features"]:
    g = f["geometry"]
    polys = g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]
    for poly in polys:
        for i, ring in enumerate(poly):
            draw.polygon([proj(x, y) for x, y in ring], fill=255 if i == 0 else 0)

img = img.resize((W, H), Image.BOX)
top = int((90 - TOP_LAT) / 180 * H)
bot = int((90 - BOTTOM_LAT) / 180 * H)


def b36(n):
    digits = "0123456789abcdefghijklmnopqrstuvwxyz"
    s = ""
    while True:
        s = digits[n % 36] + s
        n //= 36
        if n == 0:
            return s


rows = []
for y in range(top, bot):
    runs, cur, n = [], 0, 0
    for x in range(W):
        v = 1 if img.getpixel((x, y)) >= 110 else 0
        if v == cur:
            n += 1
        else:
            runs.append(n)
            cur, n = v, 1
    runs.append(n)
    rows.append(",".join(b36(r) for r in runs))

encoded = ";".join(rows)
print("// Generated by design/world-map/build_world_mask.py — do not edit by hand.")
print("package de.koenidv.spheres.domain")
print()
print("internal const val WORLD_MASK_COLS = %d" % W)
print("internal const val WORLD_MASK_ROWS = %d" % (bot - top))
print()
print('internal const val WORLD_MASK_RLE = "%s"' % encoded)
