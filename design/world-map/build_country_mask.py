"""Rasterises Natural Earth 50m countries into a per-cell country id grid (same grid as the land mask).

Usage: python3 build_country_mask.py ne_50m_admin_0_countries.geojson > WorldCountryData.kt
Id 0 is "no country". Rows are runs of `id.length` (base 36), comma separated, rows joined by ';'.
The renderer draws a border wherever two neighbouring land cells have different ids.
"""
import json
import sys

from PIL import Image, ImageDraw

W, H = 720, 360
TOP_LAT, BOTTOM_LAT = 84, -58
CHUNK = 12000

data = json.load(open(sys.argv[1]))
img = Image.new("I", (W, H), 0)
draw = ImageDraw.Draw(img)


def proj(x, y):
    return ((x + 180) / 360 * W, (90 - y) / 180 * H)


def area(feature):
    g = feature["geometry"]
    polys = g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]
    total = 0
    for poly in polys:
        xs = [p[0] for p in poly[0]]
        ys = [p[1] for p in poly[0]]
        total += (max(xs) - min(xs)) * (max(ys) - min(ys))
    return total


features = [f for f in data["features"] if f.get("geometry")]
# Big countries first so small enclaves stay visible on top.
for idx, f in enumerate(sorted(features, key=area, reverse=True), start=1):
    g = f["geometry"]
    polys = g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]
    for poly in polys:
        draw.polygon([proj(x, y) for x, y in poly[0]], fill=idx)
        for hole in poly[1:]:
            pass  # holes (lakes/enclaves) are drawn by their own features

top = int((90 - TOP_LAT) / 180 * H)
bot = int((90 - BOTTOM_LAT) / 180 * H)


def b36(n):
    digits = "0123456789abcdefghijklmnopqrstuvwxyz"
    s = ""
    while True:
        s = digits[n % 36] + s
        n //= 36
        if n == 0:
            return s


rows = []
for y in range(top, bot):
    runs, cur, n = [], img.getpixel((0, y)), 0
    for x in range(W):
        v = img.getpixel((x, y))
        if v == cur:
            n += 1
        else:
            runs.append("%s.%s" % (b36(cur), b36(n)))
            cur, n = v, 1
    runs.append("%s.%s" % (b36(cur), b36(n)))
    rows.append(",".join(runs))

encoded = ";".join(rows)
chunks = [encoded[i:i + CHUNK] for i in range(0, len(encoded), CHUNK)]
print("// Generated by design/world-map/build_country_mask.py — do not edit by hand.")
print("package de.koenidv.spheres.domain")
print()
print("internal val WORLD_COUNTRY_RLE: String = listOf(")
for c in chunks:
    print('    "%s",' % c)
print(").joinToString(\"\")")
