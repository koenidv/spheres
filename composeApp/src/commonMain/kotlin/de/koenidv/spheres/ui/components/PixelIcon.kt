private val ICON_RUNS: Map<IconName, List<PixelRect>> = GRIDS.mapValues { (_, rows) ->
    val runs = mutableListOf<PixelRect>()
    rows.forEachIndexed { y, row ->
        var x = 0
        while (x < row.length) {
            if (row[x] != '#') {
                x++
                continue
            }
            var w = 0
            while (x + w < row.length && row[x + w] == '#') {
                w++
            }
            runs.add(PixelRect(x, y, w))
            x += w
        }
    }
    runs
}

@Composable
fun PixelIcon(
    name: IconName,
    modifier: Modifier = Modifier,
    size: Dp = 24.dp,
    tint: Color = LocalContentColor.current
) {
    val runs = remember(name) { ICON_RUNS[name] ?: emptyList() }
    Canvas(modifier = modifier.size(size)) {
        val stepX = this.size.width / 12f
        val stepY = this.size.height / 12f
        for (r in runs) {
            drawRect(
                color = tint,
                topLeft = Offset(r.x * stepX, r.y * stepY),
                size = Size(r.w * stepX, stepY)
            )
        }
    }
}
